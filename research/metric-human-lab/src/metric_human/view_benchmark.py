"""Subject-held-out *synthetic in-basis* assessment of view-planning usefulness.

Test geometry is generated by the SAME body-prior basis being fitted, but with
coefficients unseen by the optimizer. This is not real-person generalization,
and camera angles, scale, pose and ideal binary masks are supplied perfectly.
The fixed baseline of front and rear views is intentionally weak for depth.
"""
from __future__ import annotations
import json
from pathlib import Path
import numpy as np
import cv2
from .prior import Prior, fit_prior_to_evidence
from .reconstruct import View
from .synthetic import render_silhouette
from .view_planner import orbit_candidates,plan_views
from .mesh_measurements import inspect_mesh_sections
from .view_centering import recenter_views_from_prior
from .robust_fit import fit_prior_coarse_to_fine


def _mesh_errors_mm(prediction,actual):
    pa=np.asarray(prediction.vertices,float)
    tr=np.asarray(actual.vertices,float)
    if pa.shape!=tr.shape: raise ValueError('Synthetic morph models must share vertex correspondence')
    err=np.linalg.norm(pa-tr,axis=1)*1000
    dims=np.abs(np.ptp(pa,axis=0)-np.ptp(tr,axis=0))*1000
    sections={}
    lb,ub=actual.bounds
    pbounds=prediction.bounds
    for frac in (.57,.76):
        z=float(lb[2]+frac*(ub[2]-lb[2]))
        if not pbounds[0,2]<z<pbounds[1,2]:continue
        trsec=inspect_mesh_sections(actual,[z])['sections'][0]['contours']
        prsec=inspect_mesh_sections(prediction,[z])['sections'][0]['contours']
        if not trsec or not prsec: continue
        sections[f'largest_horizontal_contour_at_{frac:.2f}_height_abs_perimeter_error_mm']=(
            abs(trsec[0]['perimeter_m']-prsec[0]['perimeter_m'])*1000)
    return {'mean_corresponding_vertex_error_mm':float(err.mean()),
            'p95_corresponding_vertex_error_mm':float(np.percentile(err,95)),
            'axis_extent_abs_errors_mm':dict(zip(('width_x','depth_y','height_z'),dims.tolist())),
            **sections}


def run_view_planning_benchmark(prior: Prior,*,samples:int=6,seed:int=1234,
                                candidate_count:int=8,select:int=2,
                                image_width:int=140,image_height:int=210,
                                maxiter:int=18,regularization:float=.0001,
                                mask_shift_px:int=0,alignment_radius_px:int=0,
                                prealign_radius_px:int=0,silhouette_loss_mode:str='pixel_iou',
                                out_path:str|Path|None=None):
    if not 1<=samples<=100 or not 2<=candidate_count<=24 or not 1<=select<=candidate_count:
        raise ValueError('Invalid sample/view count')
    if len(prior.parameter_names)>8 or not len(prior.parameter_names):
        raise ValueError('For now, benchmark only 1..8 editable anatomical shape parameters')
    if not 48<=image_width or not 48<=image_height or not 1<=maxiter<=200:
        raise ValueError('Invalid image/fit resolution')
    if not isinstance(mask_shift_px,int) or not 0<=mask_shift_px<=8:
        raise ValueError('mask_shift_px must be integer 0..8')
    if not isinstance(alignment_radius_px,int) or not 0<=alignment_radius_px<=8:
        raise ValueError('alignment_radius_px must be integer 0..8')
    if not isinstance(prealign_radius_px,int) or not 0<=prealign_radius_px<=8:
        raise ValueError('prealign_radius_px must be integer 0..8')
    if silhouette_loss_mode not in ('pixel_iou','profile','coarse_to_fine'):
        raise ValueError('Invalid silhouette loss mode')
    candidates=orbit_candidates(prior,count=candidate_count,width=image_width,height=image_height)
    plan=plan_views(prior,candidates,select=select)
    by_label={v.label:i for i,v in enumerate(candidates)}
    planned=[by_label[entry['label']] for entry in plan['selected']]
    # Fixed equi-angular baseline; 2 cameras means the same frontal/rear view
    # redundancy that can make front/back torso dimension unobservable.
    uniform=[int(round(i*candidate_count/select))%candidate_count for i in range(select)]
    if len(set(uniform))!=select:
        raise RuntimeError('View baseline contains duplicate camera')
    rng=np.random.default_rng(seed)
    coefficients=rng.uniform(-.6,.6,size=(samples,len(prior.parameter_names)))
    noise_rng=np.random.default_rng(seed+918273)
    rows=[]
    for body_number,coeff in enumerate(coefficients):
        actual=prior.generate(coeff)
        # Generate once per subject/candidate, and reuse the SAME perturbed mask
        # in both selection strategies to avoid unequal artificial noise.
        masks=[]
        for candidate in candidates:
            fg=np.asarray(render_silhouette(actual,candidate.camera),np.uint8)
            if mask_shift_px:
                delta=noise_rng.integers(-mask_shift_px,mask_shift_px+1,size=2)
                matrix=np.array([[1.,0.,float(delta[0])],[0.,1.,float(delta[1])]])
                fg=cv2.warpAffine(fg,matrix,(candidate.camera.width,candidate.camera.height),
                                  flags=cv2.INTER_NEAREST,borderMode=cv2.BORDER_CONSTANT,borderValue=0)
            masks.append(fg.astype(bool))
        cases={}
        for label,indices in [('planned',planned),('uniform_baseline',uniform)]:
            views=[View(candidates[i].camera,masks[i],label=candidates[i].label) for i in indices]
            centering=None
            if prealign_radius_px:
                views,centering=recenter_views_from_prior(prior,views,max_shift_px=prealign_radius_px)
            if silhouette_loss_mode=='coarse_to_fine':
                if prealign_radius_px or alignment_radius_px:
                    raise ValueError('coarse_to_fine owns centering adjustments')
                fit,diagnostics=fit_prior_coarse_to_fine(prior,views,
                   shift_limit_px=max(3,mask_shift_px),regularization=regularization,
                   coarse_maxiter=maxiter,fine_maxiter=maxiter)
            else:
                fit,diagnostics=fit_prior_to_evidence(prior,views,regularization=regularization,
                    maxiter=maxiter,alignment_radius_px=alignment_radius_px,
                    silhouette_loss_mode=silhouette_loss_mode)
            cases[label]={'prealignment_diagnostic':centering,'camera_labels':[candidates[i].label for i in indices],
                          'fitted_coefficients':[float(diagnostics['coefficients'][p]) for p in prior.parameter_names],
                          'optimizer_success':diagnostics['optimization_success'],
                          'mean_observed_mask_iou':float(np.mean([v['silhouette_iou'] for v in diagnostics['per_view_reprojection']])),
                          **_mesh_errors_mm(fit,actual)}
        rows.append({'synthetic_subject_index':body_number,
                     'ground_truth_coefficients':dict(zip(prior.parameter_names,coeff.tolist())),
                     'cases':cases})
    summary={}
    for label in ('planned','uniform_baseline'):
        errors=np.asarray([r['cases'][label]['mean_corresponding_vertex_error_mm'] for r in rows])
        summary[label]={'mean_vertex_error_mm':float(errors.mean()),
                        'median_vertex_error_mm':float(np.median(errors)),
                        'worst_vertex_error_mm':float(errors.max())}
    result={'benchmark_type':'held_out_coefficients_same_synthetic_prior_with_optional_mask_jitter',
            'source_prior':prior.source,
            'known_camera_positions_and_absolute_scale':True,
            'no_real_RGB_or_new_people':True,
            'out_of_shape_basis_generalization_tested':False,
            'synthetic_test_subjects':samples,'seed':seed,
            'segmentation_mask_integer_translation_perturbation_max_px':mask_shift_px,
            'image_centering_nuisance_alignment_radius_px':alignment_radius_px,
            'prealignment_radius_px':prealign_radius_px,
            'silhouette_loss_mode':silhouette_loss_mode,
            'parameters':list(prior.parameter_names),
            'view_selection_method':plan['method'],
            'planned_labels': [candidates[i].label for i in planned],
            'uniform_baseline_labels':[candidates[i].label for i in uniform],
            'subject_results':rows,'summary':summary,
            'notes':['This is an intentionally favorable in-basis test: the truth and fit share a shape basis.',
                     'Camera, pose and scale are known exactly; imagery is rendered binary masks (optionally pixel-translated).',
                     'The frontal/rear uniform two-view baseline is intentionally weak for torso depth.',
                     'Measured vertex errors are corresponding-vertex distances to a generated source mesh, not real-person accuracy.']}
    if out_path is not None:
        path=Path(out_path);path.parent.mkdir(parents=True,exist_ok=True)
        path.write_text(json.dumps(result,indent=2),encoding='utf8')
    return result
